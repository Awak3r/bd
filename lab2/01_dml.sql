-- ВАЖНО: файл рассчитан на выполнение в autocommit-режиме (psql -f).
-- НЕ оборачивайте весь файл в общую транзакцию: пункт 5 намеренно
-- демонстрирует частичный откат через ROLLBACK.
--
-- Порядок применения: сначала миграции 0001 (схема) и 0002 (данные).
-- Данные, создаваемые этим сценарием, используют диапазон id 200000+,
-- чтобы не пересекаться с миграцией 0002 (100000-199999).
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. INSERT: добавление новой сущности и связанных с ней записей.
--    Добавляем дисциплину «Компьютерные сети» (кафедра 806), открываем
--    по ней курс для группы М8О-301БВ-24 и открываем ведомости студентам.
-- ----------------------------------------------------------------------------

INSERT INTO disciplines (id, department_id, name, credits)
VALUES (21, 4, 'Компьютерные сети', 4);

INSERT INTO courses (id, discipline_id, group_id, teacher_id, semester, academic_year)
VALUES (31, 21, 1, 18, 5, 2026);

INSERT INTO grades (id, course_id, student_id, attempt_number, status, grade_value, assigned_on, graded_on) VALUES
    (200001, 31, 1, 1, 'assigned', NULL, '2026-11-16', NULL),
    (200002, 31, 2, 1, 'assigned', NULL, '2026-11-16', NULL),
    (200003, 31, 3, 1, 'assigned', NULL, '2026-11-16', NULL);

-- ----------------------------------------------------------------------------
-- 2. UPDATE: изменение состояния существующей операции.
--    Студент 1 сдал «Теорию оптимизации и численные методы» (курс 5):
--    ведомость в статусе assigned переводится в passed с оценкой и датой.
--    CHECK-ограничение chk_grades_status_consistency требует, чтобы при
--    статусе passed появились и оценка, и дата выставления.
-- ----------------------------------------------------------------------------

UPDATE grades
SET status = 'passed',
    grade_value = 4,
    graded_on = '2026-11-15'
WHERE student_id = 1
  AND course_id = 5
  AND attempt_number = 1
  AND status = 'assigned';

-- ----------------------------------------------------------------------------
-- 3. Массовое изменение нескольких записей по содержательному условию.
--    Курс 10 (Численные методы) переносится на следующий семестр: все его
--    открытые ведомости (assigned) аннулируются. Итоговые оценки и даты
--    при аннулировании очищаются (требование chk_grades_status_consistency).
--    Затрагиваются ведомости студентов 6 и 8 — две записи.
-- ----------------------------------------------------------------------------

UPDATE grades
SET status = 'annulled',
    grade_value = NULL,
    graded_on = NULL
WHERE course_id = 10
  AND status = 'assigned';

-- ----------------------------------------------------------------------------
-- 4. DELETE: удаление записи с учётом ограничений целостности.
--    а) Попытка удалить курс 2, по которому уже открыты ведомости:
--       внешний ключ fk_grades_course (ON DELETE RESTRICT) отклоняет удаление.
--       Ошибка перехватывается, чтобы сценарий продолжил работу.
--    б) Удаление записи, на которую никто не ссылается: ведомость студента 8
--       по курсу 10 была аннулирована в п.3 и закрывается ошибочной —
--       удаляется без нарушения целостности.
-- ----------------------------------------------------------------------------

DO $$
BEGIN
    DELETE FROM courses WHERE id = 2;
EXCEPTION
    WHEN foreign_key_violation THEN
        RAISE NOTICE 'Ожидаемо: удаление курса 2 запрещено — есть связанные ведомости (fk_grades_course, ON DELETE RESTRICT)';
END $$;

DELETE FROM grades
WHERE student_id = 8
  AND course_id = 10
  AND attempt_number = 1;

-- ----------------------------------------------------------------------------
-- 5. Демонстрация отмены изменений с помощью ROLLBACK.
--    Внутри транзакции «портим» ведомости отличника (студент 5), убеждаемся
--    в изменении выборкой, затем полностью откатываем транзакцию и снова
--    проверяем: данные вернулись к исходным.
-- ----------------------------------------------------------------------------

BEGIN;

UPDATE grades
SET grade_value = 2
WHERE student_id = 5;

SELECT id, course_id, grade_value
FROM grades
WHERE student_id = 5
ORDER BY course_id, attempt_number;

ROLLBACK;

-- Данные студента 5 не изменились: транзакция откатана целиком.
SELECT id, course_id, grade_value
FROM grades
WHERE student_id = 5
ORDER BY course_id, attempt_number;
